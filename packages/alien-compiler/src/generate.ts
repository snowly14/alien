import { randomUUID } from "node:crypto";
import { mkdir, readdir, readFile, rename, rm, writeFile } from "node:fs/promises";
import { dirname, join, relative, resolve } from "node:path";
import { prepareProject } from "./configuration.ts";
import { moduleIdentity, projectNamespace } from "./identity.ts";
import { resetCss } from "./reset.ts";

const moduleHeader = "// Generated by Alien. Do not edit.\n";
const cssHeader = "/* Generated by Alien. Do not edit. */\n";
export const isStyleSource = (path: string) => /\.alien\.(?:[cm]?ts|[cm]?js)$/.test(path);
const isGenerated = (path: string) => /\.alien\.generated\.(?:[cm]?ts|[cm]?js)$/.test(path);

export type GenerateOptions = { source?: string; globals?: string; namespace?: string };

async function readOptional(path: string) {
  try {
    return await readFile(path, "utf8");
  } catch (error) {
    if (error instanceof Error && "code" in error && error.code === "ENOENT") return undefined;
    throw error;
  }
}

async function discover(directory: string): Promise<string[]> {
  const files: string[] = [];
  for (const entry of await readdir(directory, { withFileTypes: true })) {
    if (["node_modules", ".git", ".alien", "dist"].includes(entry.name)) continue;
    const path = join(directory, entry.name);
    if (entry.isDirectory()) files.push(...(await discover(path)));
    else if (entry.isFile() && (isStyleSource(path) || isGenerated(path))) files.push(path);
  }
  return files.sort();
}

async function writeGenerated(path: string, contents: string) {
  const previous = await readOptional(path);
  if (previous === contents) return;
  await mkdir(dirname(path), { recursive: true });
  const temporary = `${path}.${randomUUID()}.tmp`;
  try {
    await writeFile(temporary, contents, "utf8");
    await rename(temporary, path);
  } finally {
    await rm(temporary, { force: true });
  }
}

/** Emit ordinary modules and a global stylesheet for any framework's build system. */
export async function generateProject(root: string, options: GenerateOptions = {}) {
  root = resolve(root);
  const sourceDirectory = resolve(root, options.source ?? "src");
  const sourceRelative = relative(root, sourceDirectory);
  if (
    sourceRelative === ".." ||
    sourceRelative.startsWith("../") ||
    sourceRelative.startsWith("..\\")
  )
    throw new Error("Alien's source directory must be inside the project root.");
  const compiler = await prepareProject(root, options.globals);
  const namespace = await projectNamespace(root, options.namespace);
  const files = await discover(sourceDirectory);
  const outputs = new Map<string, string>();
  const sources = [];
  for (const path of files.filter(isStyleSource)) {
    sources.push({
      source: await readFile(path, "utf8"),
      path,
      moduleId: moduleIdentity(root, namespace, path).id,
    });
  }
  const project = compiler.transformProject(sources);
  for (const [index, input] of sources.entries()) {
    const output = project.modules[index];
    if (!output) throw new Error(`Missing compiled output for ${input.path}`);
    const generated = input.path.replace(/\.alien\.(.+)$/, ".alien.generated.$1");
    outputs.set(generated, moduleHeader + output.code);
  }
  const css = cssHeader + resetCss(compiler.reset) + project.css;
  const cssPath = join(root, ".alien", "styles.css");
  outputs.set(cssPath, css);
  // Validate the whole plan before replacing or deleting any generated output.
  for (const path of outputs.keys()) {
    const previous = await readOptional(path);
    const header = path === cssPath ? cssHeader : moduleHeader;
    if (previous !== undefined && !previous.startsWith(header))
      throw new Error(`Refusing to overwrite ${path}: it was not generated by Alien.`);
  }
  const stale: string[] = [];
  for (const path of files.filter(isGenerated)) {
    if (outputs.has(path)) continue;
    if ((await readOptional(path))?.startsWith(moduleHeader)) stale.push(path);
  }
  for (const [path, contents] of outputs) await writeGenerated(path, contents);
  for (const path of stale) await rm(path, { force: true });
  return { modules: outputs.size - 1, cssPath, sourceDirectory };
}
