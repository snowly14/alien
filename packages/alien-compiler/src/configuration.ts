import { readFile, writeFile } from "node:fs/promises";
import { resolve } from "node:path";
import { loadCompiler, type NativeCompiler } from "./native.ts";

const generatedHeader = "// Generated by Alien. Do not edit.\n";

export function projectDeclarations(compiler: NativeCompiler): string {
  const families = new Map<string, string[]>();
  for (const path of compiler.tokenPaths) {
    const separator = path.indexOf(".");
    const family = path.slice(0, separator);
    const name = path.slice(separator + 1);
    const names = families.get(family) ?? [];
    names.push(name);
    families.set(family, names);
  }
  const tokens = [...families]
    .sort(([a], [b]) => a.localeCompare(b))
    .map(
      ([family, names]) =>
        `      ${JSON.stringify(family)}: ${names
          .sort()
          .map((name) => JSON.stringify(name))
          .join(" | ")};`,
    )
    .join("\n");
  return `${generatedHeader}import "alien";\ndeclare module "alien" {\n  interface AlienProject {\n    mode: ${JSON.stringify(compiler.mode)};\n    tokens: {\n${tokens}\n    };\n  }\n}\n`;
}

async function readOptional(path: string): Promise<string | undefined> {
  try {
    return await readFile(path, "utf8");
  } catch (error) {
    if (error instanceof Error && "code" in error && error.code === "ENOENT") return undefined;
    throw error;
  }
}

/** Also used by the CLI, so type generation works before the first Vite build. */
export async function prepareProject(root: string, globalsFile?: string): Promise<NativeCompiler> {
  const path = resolve(root, globalsFile ?? "alien.globals.ts");
  const source = await readOptional(path);
  if (source === undefined && globalsFile !== undefined)
    throw new Error(`Alien configuration not found: ${path}`);
  const compiler = loadCompiler(source, path);
  const typesPath = resolve(root, "alien-env.d.ts");
  const existing = await readOptional(typesPath);
  const declaration = projectDeclarations(compiler);
  if (existing !== declaration) {
    if (existing !== undefined && !existing.startsWith(generatedHeader)) {
      throw new Error(`Refusing to overwrite ${typesPath}: it was not generated by Alien.`);
    }
    await writeFile(typesPath, declaration, "utf8");
  }
  return compiler;
}
